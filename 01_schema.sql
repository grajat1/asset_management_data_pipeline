-- Silver: accepted canonical transactions and explicit rejects.
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID VARCHAR2(30) PRIMARY KEY,
    PORTFOLIO_ID VARCHAR2(20) NOT NULL,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    TRADE_DATE DATE NOT NULL,
    QUANTITY NUMBER(18,4) NOT NULL,
    PRICE NUMBER(18,6) NOT NULL,
    CURRENCY VARCHAR2(3) NOT NULL,
    SOURCE_FILE VARCHAR2(200) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER NOT NULL,
    RUN_ID NUMBER NOT NULL,
    RECORD_HASH VARCHAR2(64) NOT NULL,
    ACCEPTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE TRANSACTION_REJECTS (
    RUN_ID NUMBER NOT NULL,
    SOURCE_FILE VARCHAR2(200) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER NOT NULL,
    TRANSACTION_ID VARCHAR2(30),
    REASON VARCHAR2(200) NOT NULL,
    DETAILS VARCHAR2(1000),
    REJECTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE GOLD_PORTFOLIO_POSITIONS (
    RUN_ID NUMBER NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    PORTFOLIO_ID VARCHAR2(20) NOT NULL,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    QUANTITY NUMBER(18,4) NOT NULL,
    MARKET_PRICE NUMBER(18,6) NOT NULL,
    MARKET_VALUE NUMBER(20,2) NOT NULL,
    PRICE_DATE DATE NOT NULL,
    PRICE_SOURCE VARCHAR2(50),
    CURRENCY VARCHAR2(3) NOT NULL,
    SOURCE_POSITION_DATE DATE NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_GOLD_POSITIONS PRIMARY KEY
      (RUN_ID, PORTFOLIO_ID, SECURITY_ID)
);

CREATE TABLE GOLD_DATA_QUALITY_EXCEPTIONS (
    RUN_ID NUMBER NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    PORTFOLIO_ID VARCHAR2(20),
    SECURITY_ID VARCHAR2(20),
    EXCEPTION_TYPE VARCHAR2(50) NOT NULL,
    DETAILS VARCHAR2(1000),
    SOURCE_POSITION_DATE DATE,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE GOLD_COMPLIANCE_EXCEPTIONS (
    RUN_ID NUMBER NOT NULL,
    TRANSACTION_ID VARCHAR2(30) NOT NULL,
    PORTFOLIO_ID VARCHAR2(20) NOT NULL,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    TRADE_DATE DATE NOT NULL,
    RESTRICTION_TYPE VARCHAR2(30) NOT NULL,
    EXCEPTION_REASON VARCHAR2(200) NOT NULL,
    SOURCE_FILE VARCHAR2(200) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_GOLD_COMPLIANCE PRIMARY KEY
      (RUN_ID, TRANSACTION_ID, RESTRICTION_TYPE)
);

CREATE INDEX IX_TX_PORT_SEC_DATE
    ON TRANSACTIONS (PORTFOLIO_ID, SECURITY_ID, TRADE_DATE);
CREATE INDEX IX_TX_SEC_DATE
    ON TRANSACTIONS (SECURITY_ID, TRADE_DATE);
CREATE INDEX IX_PRICE_DATE
    ON MARKET_PRICES (SECURITY_ID, PRICE_DATE);
CREATE INDEX IX_RESTRICTED_DATES
    ON RESTRICTED_SECURITIES (SECURITY_ID, EFFECTIVE_FROM, EFFECTIVE_TO);
