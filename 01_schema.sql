-- Run as a dedicated schema owner. This script is not idempotent:
-- drop/recreate only in a disposable assessment schema if rerunning it.
CREATE TABLE SECURITY_MASTER (
    SECURITY_ID VARCHAR2(20) PRIMARY KEY,
    ISIN VARCHAR2(20),
    ASSET_CLASS VARCHAR2(30),
    CURRENCY VARCHAR2(3),
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE
);

CREATE TABLE POSITIONS (
    PORTFOLIO_ID VARCHAR2(20) NOT NULL,
    SECURITY_ID VARCHAR2(20) NOT NULL,
    POSITION_DATE DATE NOT NULL,
    QUANTITY NUMBER(18,4),
    BOOK_VALUE NUMBER(18,2),
    CURRENCY VARCHAR2(3),
    CONSTRAINT PK_POSITIONS PRIMARY KEY (PORTFOLIO_ID, SECURITY_ID, POSITION_DATE)
);

CREATE TABLE MARKET_PRICES (
    SECURITY_ID VARCHAR2(20) NOT NULL,
    PRICE_DATE DATE NOT NULL,
    PRICE NUMBER(18,6),
    PRICE_CURRENCY VARCHAR2(3),
    PRICE_SOURCE VARCHAR2(50),
    CONSTRAINT PK_MARKET_PRICES PRIMARY KEY (SECURITY_ID, PRICE_DATE, PRICE_SOURCE)
);

CREATE TABLE RESTRICTED_SECURITIES (
    SECURITY_ID VARCHAR2(20) NOT NULL,
    RESTRICTION_TYPE VARCHAR2(30) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    STATUS VARCHAR2(20),
    CONSTRAINT PK_RESTRICTED PRIMARY KEY
      (SECURITY_ID, RESTRICTION_TYPE, EFFECTIVE_FROM)
);

CREATE TABLE PIPELINE_RUNS (
    RUN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUSINESS_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    STARTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    RECEIVED_COUNT NUMBER DEFAULT 0 NOT NULL,
    ACCEPTED_COUNT NUMBER DEFAULT 0 NOT NULL,
    REJECTED_COUNT NUMBER DEFAULT 0 NOT NULL,
    DUPLICATE_COUNT NUMBER DEFAULT 0 NOT NULL,
    ERROR_MESSAGE VARCHAR2(1000),
    ELAPSED_SECONDS NUMBER
);

CREATE TABLE FILE_DELIVERIES (
    FILE_HASH VARCHAR2(64) PRIMARY KEY,
    FILE_NAME VARCHAR2(200) NOT NULL,
    RUN_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    RECEIVED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_DELIVERY_RUN FOREIGN KEY (RUN_ID)
      REFERENCES PIPELINE_RUNS(RUN_ID)
);

